#!/usr/bin/env python3
"""Check a team's work-shape record against the shape rule and the team tree.

A-Team decides the shape of the work before it builds a team. The decision is
recorded per user flow in ``docs/work-shape.json``:

    {"flows": [{"name": "weekly-newsletter",
                "shape": "skill-workflow",
                "parallel": "",
                "isolated_check": "",
                "overflow": "",
                "why": "One owner, one context: research, draft, source check."}]}

``shape`` is ``skill-workflow`` (one agent that loads skills) or ``agent-group``.
The three trigger fields hold evidence text, or an empty string when the trigger
does not apply:

- ``parallel``: branches that really run at the same time, each in a context
  that can be thrown away afterwards.
- ``isolated_check``: a check that must be made by someone who did not see the
  author's reasoning.
- ``overflow``: why the work would not fit in one context.

The rule: a flow with no trigger is a skill workflow; a flow with at least one
trigger is an agent group. The method and its judgement calls live in
``.claude/skills/work-shape/SKILL.md``; this script only checks that the record
obeys the rule and that the generated tree matches the record.

Usage:
    check_work_shape.py <team-root> [--surface claude|codex]

Output: one ``{id} {name} | PASS|FAIL|SKIP | {evidence}`` line per check, then
``PROFILE skill-workflow|agent-group|legacy``. Exit 1 when any check fails.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

RECORD_PATH = "docs/work-shape.json"
SHAPES = ("skill-workflow", "agent-group")
TRIGGERS = ("parallel", "isolated_check", "overflow")
# Teams stamped on or after this date must carry a record. Earlier teams were
# built under the old contract and are validated as legacy when they have none.
RECORD_REQUIRED_SINCE = "2026-11-26"

Check = tuple[str, str, str, str]


def generator_stamp(root: Path) -> str | None:
    for entry in ("CLAUDE.md", "AGENTS.md"):
        path = root / entry
        if not path.is_file():
            continue
        match = re.search(r"Generated by A-Team on (\d{4}-\d{2}-\d{2})", path.read_text(encoding="utf-8", errors="replace"))
        if match:
            return match.group(1)
    return None


def load_record(root: Path) -> tuple[list[dict] | None, str | None]:
    """Return (flows, error). Both are None when the team has no record."""
    path = root / RECORD_PATH
    if not path.is_file():
        return None, None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return None, f"{RECORD_PATH} does not parse: {exc}"
    flows = data.get("flows") if isinstance(data, dict) else None
    if not isinstance(flows, list) or not flows:
        return None, f"{RECORD_PATH} needs a non-empty 'flows' list"
    problems: list[str] = []
    for index, flow in enumerate(flows):
        label = flow.get("name") if isinstance(flow, dict) and isinstance(flow.get("name"), str) and flow.get("name") else f"flows[{index}]"
        if not isinstance(flow, dict):
            problems.append(f"{label}: not an object")
            continue
        if label.startswith("flows["):
            problems.append(f"{label}: missing name")
        if flow.get("shape") not in SHAPES:
            problems.append(f"{label}: shape must be one of {', '.join(SHAPES)}")
        for trigger in TRIGGERS:
            if not isinstance(flow.get(trigger), str):
                problems.append(f"{label}: {trigger} must be evidence text, or \"\" when it does not apply")
        if not isinstance(flow.get("why"), str) or not flow["why"].strip():
            problems.append(f"{label}: missing why")
    if problems:
        return None, "; ".join(problems[:6])
    return flows, None


def triggers_of(flow: dict) -> list[str]:
    return [trigger for trigger in TRIGGERS if flow[trigger].strip()]


def expected_shape(flow: dict) -> str:
    """The shape rule: no trigger means one agent with skills."""
    return "agent-group" if triggers_of(flow) else "skill-workflow"


def rule_problems(flows: list[dict]) -> list[str]:
    problems: list[str] = []
    for flow in flows:
        fired = triggers_of(flow)
        if flow["shape"] == "agent-group" and not fired:
            problems.append(
                f"{flow['name']}: agent-group chosen for a single-context flow "
                "(no parallel, isolated_check, or overflow evidence); use skill-workflow"
            )
        elif flow["shape"] == "skill-workflow" and fired:
            problems.append(
                f"{flow['name']}: skill-workflow chosen for a flow that needs a group "
                f"({', '.join(fired)} evidence recorded); use agent-group"
            )
    return problems


def team_profile(flows: list[dict]) -> str:
    return "agent-group" if any(flow["shape"] == "agent-group" for flow in flows) else "skill-workflow"


def count_agents(root: Path, surface: str) -> int:
    if surface == "codex":
        return len(list((root / "agents").glob("**/*.toml")))
    return len(list((root / ".claude/agents").glob("**/*.md")))


def count_skills(root: Path, surface: str) -> int:
    base = root / (".agents/skills" if surface == "codex" else ".claude/skills")
    return len(list(base.glob("*/SKILL.md")))


def tree_problems(root: Path, surface: str, profile: str) -> tuple[list[str], str]:
    agents = count_agents(root, surface)
    skills = count_skills(root, surface)
    evidence = f"{agents} agent definition(s), {skills} skill(s) on the {surface} surface"
    problems: list[str] = []
    if profile == "skill-workflow":
        if agents > 1:
            problems.append(f"record says skill-workflow but the tree defines {agents} agents; one agent that loads skills needs at most one")
        if skills == 0:
            problems.append("record says skill-workflow but the tree has no skill to load")
    elif agents < 2:
        problems.append(f"record says agent-group but the tree defines {agents} agent(s); a group needs a coordinator and at least one more agent")
    return problems, evidence


def profile_of(root: Path) -> str:
    """Profile used by the validators to pick which checks apply."""
    flows, error = load_record(root)
    if flows is None or error:
        return "legacy"
    return team_profile(flows)


def evaluate(root: Path, surface: str = "claude") -> tuple[str, list[Check]]:
    flows, error = load_record(root)
    if error:
        return "legacy", [
            ("W1", "work-shape-record", "FAIL", error),
            ("W2", "work-shape-rule", "SKIP", "record unusable (see W1)"),
            ("W3", "work-shape-tree", "SKIP", "record unusable (see W1)"),
        ]
    if flows is None:
        stamp = generator_stamp(root)
        if stamp and stamp >= RECORD_REQUIRED_SINCE:
            verdict, evidence = "FAIL", f"no {RECORD_PATH}; teams stamped {RECORD_REQUIRED_SINCE} or later record the shape decision (stamp {stamp})"
        else:
            verdict, evidence = "SKIP", f"no {RECORD_PATH}; stamp {stamp or 'absent'} predates {RECORD_REQUIRED_SINCE}, validated as a legacy team"
        return "legacy", [
            ("W1", "work-shape-record", verdict, evidence),
            ("W2", "work-shape-rule", "SKIP", "no record (see W1)"),
            ("W3", "work-shape-tree", "SKIP", "no record (see W1)"),
        ]

    profile = team_profile(flows)
    summary = ", ".join(f"{flow['name']}={flow['shape']}" for flow in flows)
    checks: list[Check] = [("W1", "work-shape-record", "PASS", f"{RECORD_PATH}: {summary}")]
    broken_rule = rule_problems(flows)
    checks.append((
        "W2",
        "work-shape-rule",
        "FAIL" if broken_rule else "PASS",
        "; ".join(broken_rule) if broken_rule else f"{len(flows)} flow(s): every group has a trigger and no skill workflow has one",
    ))
    broken_tree, tree_evidence = tree_problems(root, surface, profile)
    checks.append((
        "W3",
        "work-shape-tree",
        "FAIL" if broken_tree else "PASS",
        "; ".join(broken_tree) if broken_tree else f"{profile}: {tree_evidence}",
    ))
    return profile, checks


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Check docs/work-shape.json against the shape rule and the team tree.")
    parser.add_argument("team", help="Team root")
    parser.add_argument("--surface", choices=("claude", "codex"), default="claude")
    args = parser.parse_args(argv)
    root = Path(args.team)
    if not root.is_dir():
        print(f"W1 work-shape-record | FAIL | no such directory: {root}")
        print("PROFILE legacy")
        return 1
    profile, checks = evaluate(root, args.surface)
    for check_id, name, verdict, evidence in checks:
        print(f"{check_id} {name} | {verdict} | {evidence}")
    print(f"PROFILE {profile}")
    return 1 if any(verdict == "FAIL" for _, _, verdict, _ in checks) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
