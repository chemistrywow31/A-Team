class Reporter:
    def __init__(self) -> None:
        self.failed = False

    def emit(self, check_id: str, name: str, verdict: str, evidence: str) -> None:
        print(f"{check_id} {name} | {verdict} | {evidence}")
        if verdict == "FAIL":
            self.failed = True


def detect_layout(root: Path) -> str:
    has_claude = (root / "CLAUDE.md").is_file() or (root / ".claude").is_dir()
    has_codex = (root / "AGENTS.md").is_file() or (root / ".codex").is_dir()
    if has_claude and has_codex:
        return "dual"
    if has_claude:
        return "claude"
    if has_codex:
        return "codex"
    return "none"


def detect_surface_reference_only(path: Path, patterns: tuple[re.Pattern[str], ...]) -> str | None:
    return first_line_with_match(path, patterns)


def detect_nonteam(root: Path, agents_cfg: dict | None, agent_tomls: list[Path]) -> str | None:
    text = "\n".join(
        read_text(root / name)
        for name in ("AGENTS.md", "README.md", "docs/AUTO-TRIGGER.md")
        if (root / name).is_file()
    ).lower()
    if any(hint in text for hint in NONTEAM_HINTS):
        return "explicit standalone package wording in root docs"
    if root.name == "teams-index":
        return "generated index/data directory"
    if not (root / "AGENTS.md").exists() and not (root / "CLAUDE.md").exists():
        json_only = list(root.glob("*.json"))
        if json_only:
            return "data-only directory with no team entry document"
    return None


def detect_activation_gate(root: Path) -> str | None:
    candidate_paths = [
        root / "AGENTS.md",
        root / "README.md",
        root / ".codex/docs/local-activation.md",
    ]
    for path in candidate_paths:
        text = read_text(path).lower()
        if not text:
            continue
        for lineno, line in enumerate(text.splitlines(), start=1):
            if any(hint in line for hint in ACTIVATION_HINTS):
                snippet = " ".join(line.strip().split())
                return f"{relpath(path)}:{lineno}: {snippet}"
    return None


def load_codex_surface(root: Path) -> tuple[dict, str | None, list[Path]]:
    cfg_path = root / ".codex/config.toml"
    cfg, err = ({}, None) if not cfg_path.is_file() else parse_toml(cfg_path)
    agent_tomls = sorted(root.glob("agents/**/*.toml"))
    return cfg, err, agent_tomls


def extract_registry_paths(root: Path, cfg: dict) -> tuple[list[tuple[str, str, Path]], list[str]]:
    entries: list[tuple[str, str, Path]] = []
    issues: list[str] = []
    agents = cfg.get("agents", {})
    base = (root / ".codex").resolve()
    if not isinstance(agents, dict):
        issues.append("top-level [agents] block is missing or not a table")
        return entries, issues
    for role, spec in agents.items():
        if not isinstance(spec, dict):
            continue
        description = spec.get("description")
        config_file = spec.get("config_file")
        if not isinstance(description, str) or not description.strip():
            issues.append(f"{role}: missing description")
        if not isinstance(config_file, str) or not config_file.strip():
            issues.append(f"{role}: missing config_file")
            continue
        entries.append((role, config_file, (base / config_file).resolve()))
    return entries, issues


def registry_identity_problems(registry_entries: list[tuple[str, str, Path]]) -> list[str]:
    """Return registry-resolution failures for referenced runtime agent TOMLs."""
    problems: list[str] = []
    for role, _, path in registry_entries:
        if not path.exists():
            problems.append(f"{role}->{relpath(path)} missing")
            continue
        if not path.is_file():
            problems.append(f"{role}->{relpath(path)} is not a regular file")
            continue
        data, err = parse_toml(path)
        if err:
            problems.append(f"{role}->{relpath(path)} parse error: {err}")
            continue
        name = data.get("name")
        if not isinstance(name, str) or not name.strip():
            problems.append(f"{role}->{relpath(path)} missing nonempty name")
        elif name != role:
            problems.append(f"{role}->{relpath(path)} name {name!r} does not equal registry id {role!r}")
    return problems


def codex_multi_agent_enabled(cfg: dict) -> bool:
    features = cfg.get("features", {})
    return isinstance(features, dict) and features.get("multi_agent") is True


def claude_surface_runnable(root: Path) -> tuple[bool, str | None]:
    claude_md = root / "CLAUDE.md"
    if not claude_md.is_file():
        return False, "missing CLAUDE.md"
    if not list(root.glob(".claude/agents/**/*.md")):
        return False, "missing .claude/agents/**/*.md"
    if not (root / ".claude/settings.json").is_file():
        return False, "missing .claude/settings.json"
    reference_only = detect_surface_reference_only(claude_md, CLAUDE_REFERENCE_PATTERNS)
    if reference_only:
        return False, reference_only
    return True, None


def codex_surface_runnable(root: Path, cfg: dict, cfg_err: str | None, agent_tomls: list[Path]) -> tuple[bool, str | None]:
    if not (root / "AGENTS.md").is_file():
        return False, "missing AGENTS.md"
    if not (root / ".codex/config.toml").is_file():
        return False, "missing .codex/config.toml"
    reference_only = detect_surface_reference_only(root / "AGENTS.md", CODEX_REFERENCE_PATTERNS)
    if reference_only:
        return False, reference_only
    if cfg_err:
        return False, f".codex/config.toml parse error: {cfg_err}"
    if not codex_multi_agent_enabled(cfg):
        return False, "features.multi_agent is not true"
    registry_entries, registry_issues = extract_registry_paths(root, cfg)
    if registry_issues:
        return False, "; ".join(registry_issues[:3])
    if not registry_entries:
        return False, "no explicit [agents.<id>] registry entries"
    registry_problems = registry_identity_problems(registry_entries)
    if registry_problems:
        return False, f"registry contract failed: {'; '.join(registry_problems[:3])}"
    return True, None


def detect_canonical_authority(root: Path, repo_self: bool = False) -> tuple[str, str]:
    evidences: list[tuple[str, str]] = []
    if repo_self:
        mapping = root / ".codex/docs/claude-to-codex-mapping.md"
        agents_md = root / "AGENTS.md"
        evidences.extend(explicit_authority_hits(mapping))
        evidences.extend(explicit_authority_hits(agents_md))
    else:
        manifest = root / ".codex/docs/format-mapping.manifest.yaml"
        mapping = root / ".codex/docs/format-mapping.md"
        agents_md = root / "AGENTS.md"
        claude_md = root / "CLAUDE.md"
        evidences.extend(explicit_authority_hits(manifest))
        evidences.extend(explicit_authority_hits(mapping))
        evidences.extend(explicit_authority_hits(agents_md))
        if claude_md.is_file():
            text = read_text(claude_md).lower()
            if "reference-only mirror" in text and "codex runtime" in text:
                evidences.append(("codex", relpath(claude_md)))
            evidences.extend(explicit_authority_hits(claude_md))
    unique = {value for value, _ in evidences}
    if not evidences:
        return "ambiguous", "no explicit canonical authority artifact found"
    if len(unique) == 1:
        value = next(iter(unique))
        sources = ", ".join(source for _, source in evidences)
        return value, sources
    sources = ", ".join(f"{value}@{source}" for value, source in evidences)
    return "ambiguous", f"conflicting declarations: {sources}"


def detect_mapping_state(root: Path, canonical_authority: str, repo_self: bool = False) -> tuple[str, str]:
    if repo_self:
        mapping = root / ".codex/docs/claude-to-codex-mapping.md"
        audit = root / ".codex/docs/claude-adaptation-audit.md"
        present = [relpath(path) for path in (mapping, audit) if path.is_file()]
        if mapping.is_file() and audit.is_file():
            if canonical_authority == "ambiguous":
                return "conflicting", ", ".join(present)
            return "complete", ", ".join(present)
        if present:
            return "legacy-only", ", ".join(present)
        return "missing", "no repo-self mapping docs found"
    mapping = root / ".codex/docs/format-mapping.md"
    manifest = root / ".codex/docs/format-mapping.manifest.yaml"
    legacy = root / ".codex/docs/legacy-coverage.md"
    present = [relpath(path) for path in (mapping, manifest, legacy) if path.is_file()]
    if mapping.is_file() and manifest.is_file():
        if canonical_authority == "ambiguous":
            return "conflicting", ", ".join(present)
        return "complete", ", ".join(present)
    if legacy.is_file():
        return "legacy-only", relpath(legacy)
    if present:
        return "legacy-only", ", ".join(present)
    return "missing", "no format-mapping artifact found"


def detect_stamp_status(
    root: Path,
    runnable_claude: bool,
    runnable_codex: bool,
    repo_self: bool = False,
) -> tuple[str, str]:
    docs: list[tuple[str, Path]] = []
    if repo_self:
        docs = [("repo", root / "AGENTS.md")]
    else:
        if runnable_codex:
            docs.append(("codex", root / "AGENTS.md"))
        if runnable_claude:
            docs.append(("claude", root / "CLAUDE.md"))
    if not docs:
        return "UNKNOWN", "no runnable entry document to stamp-check"
    failures: list[str] = []
    passes: list[str] = []
    exact_dates: dict[str, str] = {}
    for label, path in docs:
        text = read_text(path)
        exact = STAMP_EXACT_RE.search(text)
        if exact:
            exact_dates[label] = exact.group(1)
            passes.append(f"{label}@{relpath(path)}={exact.group(1)}")
            continue
        partial = STAMP_PARTIAL_RE.search(text)
        if partial:
            failures.append(f"{label}@{relpath(path)}={partial.group(1).strip()}")
        else:
            failures.append(f"{label}@{relpath(path)}=missing")
    if failures:
        return "FAIL", "; ".join(failures + passes)
    if len(exact_dates) > 1 and len(set(exact_dates.values())) != 1:
        return "FAIL", f"runnable surface generator dates differ: {'; '.join(passes)}"
    return "PASS", "; ".join(passes)


def classify_team(root: Path, repo_self: bool = False) -> Classification:
    if repo_self:
        canonical_authority, canonical_evidence = detect_canonical_authority(root, repo_self=True)
        mapping_state, mapping_evidence = detect_mapping_state(root, canonical_authority, repo_self=True)
        stamp_status, stamp_evidence = detect_stamp_status(root, False, True, repo_self=True)
        return Classification(
            layout="codex",
            runnable_claude=False,
            runnable_codex=True,
            team_class="repo-self",
            reason="A-Team project root",
            canonical_authority=canonical_authority,
            canonical_evidence=canonical_evidence,
            mapping_state=mapping_state,
            mapping_evidence=mapping_evidence,
            stamp_status=stamp_status,
            stamp_evidence=stamp_evidence,
        )

    cfg, cfg_err, agent_tomls = load_codex_surface(root)
    nonteam = detect_nonteam(root, cfg, agent_tomls)
    if nonteam:
        canonical_authority, canonical_evidence = detect_canonical_authority(root)
        mapping_state, mapping_evidence = detect_mapping_state(root, canonical_authority)
        stamp_status, stamp_evidence = detect_stamp_status(root, False, False)
        return Classification(
            layout=detect_layout(root),
            runnable_claude=False,
            runnable_codex=False,
            team_class="non-team package/data",
            reason=nonteam,
            canonical_authority=canonical_authority,
            canonical_evidence=canonical_evidence,
            mapping_state=mapping_state,
            mapping_evidence=mapping_evidence,
            stamp_status=stamp_status,
            stamp_evidence=stamp_evidence,
        )

    activation = detect_activation_gate(root)
    layout = detect_layout(root)
    claude_ok, claude_reason = claude_surface_runnable(root)
    codex_ok, codex_reason = codex_surface_runnable(root, cfg, cfg_err, agent_tomls)
    canonical_authority, canonical_evidence = detect_canonical_authority(root)
    mapping_state, mapping_evidence = detect_mapping_state(root, canonical_authority)
    stamp_status, stamp_evidence = detect_stamp_status(root, claude_ok, codex_ok)

    if activation:
        return Classification(
            layout=layout,
            runnable_claude=claude_ok,
            runnable_codex=codex_ok,
            team_class="incomplete/activation-gated",
            reason=activation,
            canonical_authority=canonical_authority,
            canonical_evidence=canonical_evidence,
            mapping_state=mapping_state,
            mapping_evidence=mapping_evidence,
            stamp_status=stamp_status,
            stamp_evidence=stamp_evidence,
            codex_reference_only=codex_reason if codex_reason and "reference" in codex_reason.lower() else None,
            claude_reference_only=claude_reason if claude_reason and "reference" in claude_reason.lower() else None,
        )

    if layout == "dual":
        if claude_ok and codex_ok:
            team_class = "dual"
            reason = "dual layout with runnable Claude and Codex surfaces"
        elif codex_ok:
            team_class = "dual"
            reason = "dual layout with Codex-only runnable surface"
        elif claude_ok:
            team_class = "dual"
            reason = "dual layout with Claude-only runnable surface"
        else:
            team_class = "incomplete/activation-gated"
            reason = codex_reason or claude_reason or "dual layout with no runnable surface"
    elif codex_ok:
        team_class = "Codex-only"
        reason = "runnable Codex surface present; Claude surface absent or non-runnable"
    elif claude_ok:
        team_class = "Claude-only"
        reason = "runnable Claude surface present; Codex surface absent or non-runnable"
    else:
        team_class = "incomplete/activation-gated"
        reason = codex_reason or claude_reason or "no runnable surface detected"

    return Classification(
        layout=layout,
        runnable_claude=claude_ok,
        runnable_codex=codex_ok,
        team_class=team_class,
        reason=reason,
        canonical_authority=canonical_authority,
        canonical_evidence=canonical_evidence,
        mapping_state=mapping_state,
        mapping_evidence=mapping_evidence,
        stamp_status=stamp_status,
        stamp_evidence=stamp_evidence,
        codex_reference_only=codex_reason if codex_reason and "reference" in codex_reason.lower() else None,
        claude_reference_only=claude_reason if claude_reason and "reference" in claude_reason.lower() else None,
    )


def run_strict_config(target: Path | None) -> tuple[bool, str]:
    if shutil_which("codex") is None:
        return False, "codex binary not found in PATH"
    cmd = [
        "codex",
        "exec",
        "--strict-config",
        "--sandbox",
        "read-only",
        "--skip-git-repo-check",
        "--ephemeral",
        "Reply with CONFIG_OK only.",
    ]
    if target is not None:
        cmd = ["codex", "-C", str(target), *cmd[1:]]
    try:
        proc = subprocess.run(
            cmd,
            cwd=str(REPO_ROOT if target is None else target),
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )
    except subprocess.TimeoutExpired:
        return False, "strict-config timed out after 60s"
    output = "\n".join(part for part in (proc.stdout.strip(), proc.stderr.strip()) if part).strip()
    output = " ".join(output.split())
    if proc.returncode == 0:
        return True, "CONFIG_OK" if "CONFIG_OK" in output else "strict-config exited 0"
    return False, output or f"strict-config exited {proc.returncode}"


def shutil_which(name: str) -> str | None:
    for directory in os.environ.get("PATH", "").split(os.pathsep):
        candidate = Path(directory) / name
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return str(candidate)
    return None


def validate_repo_self(reporter: Reporter, root: Path) -> None:
    classification = classify_team(root, repo_self=True)
    reporter.emit("R0", "repo-self-target", "PASS", relpath(root))
    reporter.emit(
        "STAMP",
        "repo-self-stamp",
        classification.stamp_status,
        classification.stamp_evidence,
    )
    authority_verdict = "PASS" if classification.canonical_authority != "ambiguous" else "FAIL"
    reporter.emit(
        "CANONICAL_AUTHORITY",
        "repo-self-canonical-authority",
        authority_verdict,
        f"{classification.canonical_authority} | {classification.canonical_evidence}",
    )
    mapping_verdict = "PASS" if classification.mapping_state == "complete" else "FAIL"
    reporter.emit(
        "MAPPING_STATE",
        "repo-self-mapping-state",
        mapping_verdict,
        f"{classification.mapping_state} | {classification.mapping_evidence}",
    )

    version_ok = shutil_which("codex") is not None
    feature_line = "codex not found"
    feature_ok = False
    version_out = ""
    if version_ok:
        version_proc = subprocess.run(
            ["codex", "--version"],
            cwd=str(root),
            capture_output=True,
            text=True,
            check=False,
        )
        version_out = " ".join((version_proc.stdout or version_proc.stderr).split()) or "unknown version"
        features_proc = subprocess.run(
            ["codex", "features", "list"],
            cwd=str(root),
            capture_output=True,
            text=True,
            check=False,
        )
        feature_lines = [
            line.strip()
            for line in features_proc.stdout.splitlines()
            if line.startswith("multi_agent")
        ]
        feature_line = "; ".join(feature_lines) if feature_lines else "no multi_agent feature rows"
        feature_ok = any(
            (parts := line.split()) and parts[0] == "multi_agent_v2" and parts[-1].lower() == "true"
            for line in feature_lines
        )
    reporter.emit(
        "R1",
        "version-features",
        "PASS" if version_ok and feature_ok else "FAIL",
        f"{version_out}; {feature_line}",
    )

    strict_ok, strict_evidence = run_strict_config(None)
    reporter.emit("R2", "strict-config", "PASS" if strict_ok else "FAIL", strict_evidence)

    cfg, cfg_err = parse_toml(root / ".codex/config.toml")
    if cfg_err:
        reporter.emit("R3", "config-toml-parses", "FAIL", cfg_err)
        reporter.emit("R4", "registry-resolution", "SKIP", "config parse failed (see R3)")
        reporter.emit("R5", "agent-toml-required-keys", "SKIP", "config parse failed (see R3)")
        reporter.emit("R6", "v2-feature-and-legacy-keys", "SKIP", "config parse failed (see R3)")
        skill_verdict, skill_evidence = validate_skill_mirror(root, required=True)
        reporter.emit("R9", "skill-mirror-parity", skill_verdict, skill_evidence)
        m5_verdict, m5_evidence = validate_m5_inventory(root)
        reporter.emit("R10", "m5-manifest-audit-parity", m5_verdict, m5_evidence)
        reporter.emit("R11", "active-runtime-vocabulary", "SKIP", "config parse failed (see R3)")
    else:
        reporter.emit("R3", "config-toml-parses", "PASS", relpath(root / ".codex/config.toml"))
        registry_entries, registry_issues = extract_registry_paths(root, cfg)
        registry_problems = registry_issues + registry_identity_problems(registry_entries)
        if registry_problems:
            reporter.emit("R4", "registry-resolution", "FAIL", "; ".join(registry_problems[:6]))
        else:
            reporter.emit(
                "R4",
                "registry-resolution",
                "PASS",
                f"{len(registry_entries)} config_file paths resolve from .codex/",
            )

        missing_keys: list[str] = []
        parsed_agent_tomls = 0
        for _, _, path in registry_entries:
            data, err = parse_toml(path)
            if err:
                continue
            parsed_agent_tomls += 1
            for key in REQUIRED_AGENT_KEYS:
                if key not in data or not isinstance(data[key], str) or not data[key].strip():
                    missing_keys.append(f"{relpath(path)} missing {key}")
        reporter.emit(
            "R5",
            "agent-toml-required-keys",
            "PASS" if not missing_keys else "FAIL",
            f"checked {parsed_agent_tomls} parseable agent TOMLs" if not missing_keys else "; ".join(missing_keys[:6]),
        )

        problems = v2_config_problems(cfg)
        reporter.emit(
            "R6",
            "v2-feature-and-legacy-keys",
            "PASS" if not problems else "FAIL",
            "v2 feature block present and current" if not problems else "; ".join(problems),
        )

        skill_verdict, skill_evidence = validate_skill_mirror(root, required=True)
        reporter.emit("R9", "skill-mirror-parity", skill_verdict, skill_evidence)
        m5_verdict, m5_evidence = validate_m5_inventory(root)
        reporter.emit("R10", "m5-manifest-audit-parity", m5_verdict, m5_evidence)
        stale_verdict, stale_evidence = validate_active_runtime_vocabulary(root, cfg, registry_entries)
        reporter.emit("R11", "active-runtime-vocabulary", stale_verdict, stale_evidence)

    reporter.emit(
        "R7",
        "protected-path-expectation",
        "PASS",
        "static scope includes .codex/ and .agents/; live writeability must be confirmed separately by runtime preflight",
    )
    live_tools = parse_live_tools_env()
    if live_tools is None:
        reporter.emit("R8", "host-tool-readiness", "SKIP", "set CODEX_PREFLIGHT_LIVE_TOOLS or use preflight-codex-runtime.sh --live-tools")
    else:
        missing = [tool for tool in REQUIRED_HOST_TOOLS if tool not in live_tools]
        reporter.emit(
            "R8",
            "host-tool-readiness",
            "PASS" if not missing else "FAIL",
            "all required collaboration tools present"
            if not missing
            else f"missing live tools: {', '.join(missing)}",
        )


def parse_live_tools_env() -> set[str] | None:
    raw = os.environ.get("CODEX_PREFLIGHT_LIVE_TOOLS", "").strip()
    if not raw:
        return None
    return {part.strip() for part in raw.split(",") if part.strip()}


def validate_team(reporter: Reporter, root: Path, classify_only: bool) -> None:
    classification = classify_team(root)
    if classification.runnable_claude and classification.runnable_codex:
        runnable = "dual"
    elif classification.runnable_codex:
        runnable = "codex-only"
    elif classification.runnable_claude:
        runnable = "claude-only"
    else:
        runnable = "none"
    base_evidence = f"layout={classification.layout}; runnable={runnable}"
    verdict = "PASS"
    if classification.team_class == "non-team package/data":
        verdict = "SKIP"
    elif classification.team_class == "Claude-only":
        verdict = "SKIP"
    elif classification.team_class == "incomplete/activation-gated":
        verdict = "FAIL"
    reporter.emit(
        "G1",
        "team-classification",
        verdict,
        f"class={classification.team_class}; {base_evidence}; reason={classification.reason}",
    )
    stamp_verdict = "SKIP" if classification.stamp_status == "UNKNOWN" else classification.stamp_status
    reporter.emit("STAMP", "team-stamp", stamp_verdict, classification.stamp_evidence)
    authority_verdict = "PASS" if classification.canonical_authority != "ambiguous" else "FAIL"
    if classification.team_class == "non-team package/data":
        authority_verdict = "SKIP"
    reporter.emit(
        "CANONICAL_AUTHORITY",
        "team-canonical-authority",
        authority_verdict,
        f"{classification.canonical_authority} | {classification.canonical_evidence}",
    )
    if classification.team_class == "non-team package/data":
        mapping_verdict = "SKIP"
    elif classification.mapping_state == "complete":
        mapping_verdict = "PASS"
    elif classification.mapping_state == "missing" and classification.team_class == "Claude-only":
        mapping_verdict = "SKIP"
    else:
        mapping_verdict = "FAIL"
    reporter.emit(
        "MAPPING_STATE",
        "team-mapping-state",
        mapping_verdict,
        f"{classification.mapping_state} | {classification.mapping_evidence}",
    )

    if classify_only:
        return
    if classification.team_class == "non-team package/data":
        reporter.emit("G2", "target-strict-config", "SKIP", "non-team package/data")
        reporter.emit("G3", "runnable-codex-surface", "SKIP", "non-team package/data")
        reporter.emit("G4", "codex-registry", "SKIP", "non-team package/data")
        reporter.emit("G5", "model-sandbox-posture", "SKIP", "non-team package/data")
        reporter.emit("G6", "write-target-posture", "SKIP", "non-team package/data")
        reporter.emit("G7", "host-tool-readiness", "SKIP", "non-team package/data")
        skill_verdict, skill_evidence = validate_skill_mirror(root, required=False)
        reporter.emit("G8", "skill-mirror-parity", skill_verdict, skill_evidence)
        reporter.emit("G9", "target-v2-config-keys", "SKIP", "non-team package/data")
        return
    if classification.team_class == "Claude-only":
        reason = "Codex runtime not applicable without user-approved conversion"
        reporter.emit("G2", "target-strict-config", "SKIP", reason)
        reporter.emit("G3", "runnable-codex-surface", "SKIP", reason)
        reporter.emit("G4", "codex-registry", "SKIP", reason)
        reporter.emit("G5", "model-sandbox-posture", "SKIP", reason)
        reporter.emit("G6", "write-target-posture", "SKIP", reason)
        reporter.emit("G7", "host-tool-readiness", "SKIP", reason)
        skill_verdict, skill_evidence = validate_skill_mirror(root, required=False)
        reporter.emit("G8", "skill-mirror-parity", skill_verdict, skill_evidence)
        reporter.emit("G9", "target-v2-config-keys", "SKIP", reason)
        return

    cfg, cfg_err, agent_tomls = load_codex_surface(root)
    strict_ok, strict_evidence = run_strict_config(root)
    reporter.emit("G2", "target-strict-config", "PASS" if strict_ok else "FAIL", strict_evidence)

    codex_ok, codex_reason = codex_surface_runnable(root, cfg, cfg_err, agent_tomls)
    reporter.emit(
        "G3",
        "runnable-codex-surface",
        "PASS" if codex_ok else "FAIL",
        "AGENTS.md + .codex/config.toml + runtime agent surface present"
        if codex_ok
        else codex_reason or "Codex surface incomplete",
    )

    registry_entries, registry_issues = extract_registry_paths(root, cfg) if not cfg_err else ([], [cfg_err])
    config_targets = {path.resolve() for _, _, path in registry_entries}
    unregistered = [relpath(path) for path in agent_tomls if path.resolve() not in config_targets] if registry_entries else []
    registry_problems = registry_issues + registry_identity_problems(registry_entries)
    if registry_entries and unregistered:
        registry_problems.append(f"unregistered agent TOMLs: {', '.join(unregistered[:4])}")
    if not registry_entries:
        registry_problems.append("no explicit [agents.<id>] registry entries")
    reporter.emit(
        "G4",
        "codex-registry",
        "PASS" if not registry_problems else "FAIL",
        f"registry pattern=explicit; roles={len(registry_entries)}"
        if registry_entries and not registry_problems
        else "; ".join(registry_problems[:6]),
    )

    if cfg_err:
        reporter.emit("G9", "target-v2-config-keys", "FAIL", f".codex/config.toml parse error: {cfg_err}")
    else:
        v2_problems = v2_config_problems(cfg)
        reporter.emit(
            "G9",
            "target-v2-config-keys",
            "PASS" if not v2_problems else "FAIL",
            "v2 feature block present and current" if not v2_problems else "; ".join(v2_problems[:6]),
        )

    role_issues: list[str] = []
    active_paths = [path for _, _, path in registry_entries] if registry_entries else agent_tomls
    for path in active_paths:
        data, err = parse_toml(path)
        if err:
            role_issues.append(f"{relpath(path)} parse error: {err}")
            continue
        for key in ("model", "model_reasoning_effort", "sandbox_mode"):
            value = data.get(key)
            if not isinstance(value, str) or not value.strip():
                role_issues.append(f"{relpath(path)} missing {key}")
        role_id = path.stem.lower()
        sandbox = str(data.get("sandbox_mode", "")).strip()
        if any(hint in role_id for hint in WRITER_ROLE_HINTS) and sandbox == "read-only":
            role_issues.append(f"{relpath(path)} writer-like role locked to read-only")
    root_text = read_text(root / "AGENTS.md")
    if "~/.codex/config.toml" in root_text and "do not require" not in root_text.lower():
        role_issues.append("AGENTS.md presents ~/.codex/config.toml as a runtime requirement")
    reporter.emit(
        "G5",
        "model-sandbox-posture",
        "PASS" if not role_issues else "FAIL",
        f"checked {len(active_paths)} active agent TOMLs"
        if not role_issues
        else "; ".join(role_issues[:6]),
    )

    write_target_evidence: list[str] = []
    if "~/.codex/config.toml" in root_text and "do not require" in root_text.lower():
        write_target_evidence.append("root doc rejects ~/.codex/config.toml dependency")
    if "project-local `.codex/config.toml`" in root_text or "project-local .codex/config.toml" in root_text:
        write_target_evidence.append("root doc uses project-local runtime config")
    if ".worklog/" in root_text:
        write_target_evidence.append("worklog stays inside package/workspace")
    reporter.emit(
        "G6",
        "write-target-posture",
        "PASS" if write_target_evidence else "SKIP",
        "; ".join(write_target_evidence)
        if write_target_evidence
        else "no explicit write-target contract found in AGENTS.md",
    )

    live_tools = parse_live_tools_env()
    if live_tools is None:
        reporter.emit("G7", "host-tool-readiness", "SKIP", "set CODEX_PREFLIGHT_LIVE_TOOLS or use preflight-codex-runtime.sh --live-tools")
    else:
        missing = [tool for tool in REQUIRED_HOST_TOOLS if tool not in live_tools]
        reporter.emit(
            "G7",
            "host-tool-readiness",
            "PASS" if not missing else "FAIL",
            "v2-ready: all required collaboration tools present"
            if not missing
            else f"unsupported for v2: missing {', '.join(missing)}",
        )

    skill_verdict, skill_evidence = validate_skill_mirror(root, required=False)
    reporter.emit("G8", "skill-mirror-parity", skill_verdict, skill_evidence)


def print_header(root: Path) -> None:
    print(f"## {relpath(root)}")


def iter_team_roots(base: Path) -> list[Path]:
    return sorted(path for path in base.iterdir() if path.is_dir())


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="Validate Codex team/runtime surfaces with deterministic classification."
    )
    parser.add_argument("target", nargs="?", help="Team root to validate")
    parser.add_argument("--repo-self", action="store_true", help="Validate the A-Team repo-self Codex surface")
    parser.add_argument("--classify", action="store_true", help="Only emit deterministic classification evidence")
    parser.add_argument("--all", action="store_true", help="Sweep every direct teams/* child")
    args = parser.parse_args(argv)

    selected = sum(bool(value) for value in (args.repo_self, args.all, args.target))
    if selected != 1:
        parser.error("pick exactly one of <target>, --repo-self, or --all")

    overall_failed = False
    if args.repo_self:
        reporter = Reporter()
        print_header(REPO_ROOT)
        validate_repo_self(reporter, REPO_ROOT)
        overall_failed = reporter.failed
    elif args.all:
        for root in iter_team_roots(TEAMS_ROOT):
            reporter = Reporter()
            print_header(root)
            validate_team(reporter, root, classify_only=args.classify)
            overall_failed = overall_failed or reporter.failed
            print()
    else:
        root = (Path(args.target).resolve() if Path(args.target).is_absolute() else (Path.cwd() / args.target).resolve())
        reporter = Reporter()
        print_header(root)
        validate_team(reporter, root, classify_only=args.classify)
        overall_failed = reporter.failed
    return 1 if overall_failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
