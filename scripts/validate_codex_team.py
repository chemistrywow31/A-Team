def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def relpath(path: Path) -> str:
    try:
        return path.relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def first_line_with_match(path: Path, patterns: Iterable[re.Pattern[str]]) -> str | None:
    if not path.is_file():
        return None
    for lineno, line in enumerate(read_text(path).splitlines(), start=1):
        for pattern in patterns:
            if pattern.search(line):
                text = " ".join(line.strip().split())
                return f"{relpath(path)}:{lineno}: {text}"
    return None


def explicit_authority_hits(path: Path) -> list[tuple[str, str]]:
    hits: list[tuple[str, str]] = []
    if not path.is_file():
        return hits
    codex_patterns = (
        re.compile(r"canonical_authored_format:\s*codex-native", re.IGNORECASE),
        re.compile(r"canonical_precedence:\s*codex", re.IGNORECASE),
        re.compile(r"canonical authored format:\s*codex", re.IGNORECASE),
        re.compile(r"codex remains canonical", re.IGNORECASE),
        re.compile(r"codex-native artifacts remain the source of truth", re.IGNORECASE),
        re.compile(r"codex-native is canonical", re.IGNORECASE),
        re.compile(r"codex is the canonical authored format", re.IGNORECASE),
        re.compile(r"canonical authored package is codex-native", re.IGNORECASE),
    )
    claude_patterns = (
        re.compile(r"canonical_authored_format:\s*claude", re.IGNORECASE),
        re.compile(r"canonical_precedence:\s*claude", re.IGNORECASE),
        re.compile(r"canonical authored format:\s*claude", re.IGNORECASE),
        re.compile(r"claude remains canonical", re.IGNORECASE),
        re.compile(r"\.claude/.*canonical source design", re.IGNORECASE),
        re.compile(r"canonical source design.*\.claude/", re.IGNORECASE),
        re.compile(r"claude is the canonical authored format", re.IGNORECASE),
    )
    dual_patterns = (
        re.compile(r"canonical_authored_format:\s*dual", re.IGNORECASE),
        re.compile(r"canonical_precedence:\s*dual", re.IGNORECASE),
        re.compile(r"dual canonical", re.IGNORECASE),
    )
    for lineno, line in enumerate(read_text(path).splitlines(), start=1):
        text = line.strip()
        if not text:
            continue
        if any(pattern.search(text) for pattern in codex_patterns):
            hits.append(("codex", f"{relpath(path)}:{lineno}"))
        if any(pattern.search(text) for pattern in claude_patterns):
            hits.append(("claude", f"{relpath(path)}:{lineno}"))
        if any(pattern.search(text) for pattern in dual_patterns):
            hits.append(("dual", f"{relpath(path)}:{lineno}"))
    return hits


def parse_toml(path: Path) -> tuple[dict, str | None]:
    try:
        with path.open("rb") as fh:
            return tomllib.load(fh), None
    except (OSError, tomllib.TOMLDecodeError) as exc:
        return {}, str(exc)


def path_exists(path: Path) -> bool:
    return path.exists()


def tree_paths(root: Path) -> set[str]:
    """Return a deterministic relative tree, including empty directories."""
    return {
        path.relative_to(root).as_posix()
        for path in root.rglob("*")
    }


def validate_skill_mirror(root: Path, required: bool) -> tuple[str, str]:
    """Check authored/runtime skill mirrors for identical paths and bytes."""
    authored = root / ".codex/skills"
    runtime = root / ".agents/skills"
    authored_present = authored.is_dir()
    runtime_present = runtime.is_dir()
    if not authored_present and not runtime_present:
        return ("FAIL" if required else "SKIP", "neither .codex/skills nor .agents/skills exists")
    if not authored_present or not runtime_present:
        missing = ".codex/skills" if not authored_present else ".agents/skills"
        return "FAIL", f"one-sided skill mirror: missing {missing}"

    authored_tree = tree_paths(authored)
    runtime_tree = tree_paths(runtime)
    if authored_tree != runtime_tree:
        only_authored = sorted(authored_tree - runtime_tree)
        only_runtime = sorted(runtime_tree - authored_tree)
        evidence: list[str] = []
        if only_authored:
            evidence.append(f"only .codex/skills: {', '.join(only_authored[:3])}")
        if only_runtime:
            evidence.append(f"only .agents/skills: {', '.join(only_runtime[:3])}")
        return "FAIL", "; ".join(evidence)

    compared = 0
    for relative in sorted(authored_tree):
        authored_path = authored / relative
        runtime_path = runtime / relative
        if authored_path.is_dir():
            continue
        if not authored_path.is_file() or not runtime_path.is_file():
            return "FAIL", f"non-file mirror mismatch at {relative}"
        compared += 1
        if authored_path.read_bytes() != runtime_path.read_bytes():
            return "FAIL", f"byte mismatch: {relative}"
    return "PASS", f"byte-identical trees; {compared} files"


def extract_audit_table_paths(audit: Path, heading: str) -> set[str]:
    """Extract first-column code paths from a named Markdown audit table."""
    in_section = False
    paths: set[str] = set()
    row_pattern = re.compile(r"^\|\s*`([^`]+)`\s*\|")
    for line in read_text(audit).splitlines():
        if line.startswith("## "):
            in_section = line.strip() == f"## {heading}"
            continue
        if in_section:
            match = row_pattern.match(line)
            if match:
                paths.add(match.group(1))
    return paths


def validate_m5_inventory(root: Path) -> tuple[str, str]:
    """Validate the machine-readable M5 inventory against its human audit."""
    manifest = root / ".codex/docs/claude-adaptation-manifest.toml"
    audit = root / ".codex/docs/claude-adaptation-audit.md"
    data, err = parse_toml(manifest)
    if err:
        return "FAIL", f"{relpath(manifest)} parse error: {err}"
    if not audit.is_file():
        return "FAIL", f"missing {relpath(audit)}"

    def manifest_paths(key: str) -> tuple[set[str], list[str]]:
        entries = data.get(key)
        if not isinstance(entries, list):
            return set(), [f"missing [[{key}]] entries"]
        paths: set[str] = set()
        issues: list[str] = []
        for entry in entries:
            path = entry.get("path") if isinstance(entry, dict) else None
            if not isinstance(path, str) or not path:
                issues.append(f"{key} entry missing path")
            elif path in paths:
                issues.append(f"duplicate {key} path: {path}")
            else:
                paths.add(path)
        return paths, issues

    platform, problems = manifest_paths("platform_only")
    omitted, omitted_problems = manifest_paths("deliberately_not_copied")
    problems.extend(omitted_problems)
    audit_platform = extract_audit_table_paths(audit, "Codex-Only Inventory")
    audit_omitted = extract_audit_table_paths(audit, "Deliberately Not Copied")
    if platform != audit_platform:
        problems.append("platform_only paths differ from audit Codex-Only Inventory")
    if omitted != audit_omitted:
        problems.append("deliberately_not_copied paths differ from audit Deliberately Not Copied")
    missing_paths = [path for path in sorted(platform) if not (root / path).exists()]
    if missing_paths:
        problems.append(f"platform-only paths missing: {', '.join(missing_paths[:4])}")
    if problems:
        return "FAIL", "; ".join(problems[:6])
    return "PASS", f"manifest/audit agree; {len(platform)} platform-only and {len(omitted)} deliberately-not-copied paths"


def v2_config_problems(cfg: dict) -> list[str]:
    """Return unsupported V1/stale config fields from an active project config."""
    v2 = cfg.get("features", {}).get("multi_agent_v2", {})
    problems: list[str] = []
    if not isinstance(v2, dict):
        problems.append("missing [features.multi_agent_v2]")
    else:
        if v2.get("enabled") is not True:
            problems.append("features.multi_agent_v2.enabled != true")
        if "max_concurrent_threads_per_session" not in v2:
            problems.append("missing features.multi_agent_v2.max_concurrent_threads_per_session")
        if v2.get("expose_spawn_agent_model_overrides") is not True:
            problems.append("missing expose_spawn_agent_model_overrides=true")
        if v2.get("wait_agent_enabled") is not True:
            problems.append("missing wait_agent_enabled=true")
    agents = cfg.get("agents", {})
    if not isinstance(agents, dict):
        problems.append("top-level [agents] block is missing or not a table")
    else:
        for key in ("max_threads", "max_depth"):
            if key in agents:
                problems.append(f"legacy agents.{key} still present")
    if "disable_response_storage" in cfg:
        problems.append("legacy root disable_response_storage still present")
    if str(cfg.get("approval_policy", "")).lower() == "on-failure":
        problems.append("deprecated approval_policy=on-failure still present")
    return problems


def validate_active_runtime_vocabulary(root: Path, cfg: dict, registry_entries: list[tuple[str, str, Path]]) -> tuple[str, str]:
    """Scan active configs plus each registry-linked authoritative playbook."""
    paths = [root / ".codex/config.toml"]
    paths.extend(path for _, _, path in registry_entries)
    issues: list[str] = []
    for path in paths:
        data, err = parse_toml(path)
        if err:
            issues.append(f"{relpath(path)} parse error")
            continue
        if path == root / ".codex/config.toml":
            agents = data.get("agents", {})
            if isinstance(agents, dict):
                for key in ("max_threads", "max_depth"):
                    if key in agents:
                        issues.append(f"{relpath(path)} legacy agents.{key}")
            if "disable_response_storage" in data:
                issues.append(f"{relpath(path)} legacy disable_response_storage")
            if str(data.get("approval_policy", "")).lower() == "on-failure":
                issues.append(f"{relpath(path)} deprecated approval_policy=on-failure")
        instructions = data.get("developer_instructions")
        if isinstance(instructions, str):
            for tool, pattern in STALE_RUNTIME_PATTERNS:
                if pattern.search(instructions):
                    issues.append(f"{relpath(path)} stale runtime tool {tool}")
    playbooks = 0
    for _, _, config_path in registry_entries:
        try:
            relative = config_path.resolve().relative_to((root / "agents").resolve())
        except ValueError:
            issues.append(f"{relpath(config_path)} is outside agents/ and cannot map to a playbook")
            continue
        playbook = root / ".codex/agents" / relative.with_suffix(".md")
        if not playbook.is_file():
            issues.append(f"missing authoritative playbook {relpath(playbook)} for {relpath(config_path)}")
            continue
        data, err = parse_toml(config_path)
        if err:
            continue
        instructions = data.get("developer_instructions")
        expected_reference = ".codex/agents/" + relative.with_suffix(".md").as_posix()
        if not isinstance(instructions, str) or expected_reference not in instructions:
            issues.append(f"broken bootstrap mapping: {relpath(config_path)} does not reference {expected_reference}")
        playbooks += 1
        text = read_text(playbook)
        for tool, pattern in STALE_RUNTIME_PATTERNS:
            if pattern.search(text):
                issues.append(f"{relpath(playbook)} stale runtime tool {tool}")
    if issues:
        return "FAIL", "; ".join(issues[:6])
    return "PASS", f"scanned {len(paths)} active TOMLs and {playbooks} mapped playbooks; no stale fields or tool vocabulary"


