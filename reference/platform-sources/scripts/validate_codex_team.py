def detect_nonteam(root: Path, agents_cfg: dict | None, agent_tomls: list[Path]) -> str | None:
    text = "\n".join(
        read_text(root / name)
        for name in ("AGENTS.md", "README.md", "docs/AUTO-TRIGGER.md")
        if (root / name).is_file()
    ).lower()
    if any(hint in text for hint in NONTEAM_HINTS):
        return "explicit standalone package wording in root docs"
    if root.name == "teams-index":
        return "generated index/data directory"
    if not (root / "AGENTS.md").exists() and not (root / "CLAUDE.md").exists():
        json_only = list(root.glob("*.json"))
        if json_only:
            return "data-only directory with no team entry document"
    return None


def detect_activation_gate(root: Path) -> str | None:
    candidate_paths = [
        root / "AGENTS.md",
        root / "README.md",
        root / ".codex/docs/local-activation.md",
    ]
    for path in candidate_paths:
        text = read_text(path).lower()
        if not text:
            continue
        for lineno, line in enumerate(text.splitlines(), start=1):
            if any(hint in line for hint in ACTIVATION_HINTS):
                snippet = " ".join(line.strip().split())
                return f"{relpath(path)}:{lineno}: {snippet}"
    return None


