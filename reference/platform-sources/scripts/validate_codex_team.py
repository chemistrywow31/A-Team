def j5_frontmatter_problems(text: str, required_fields: tuple[str, ...]) -> list[str]:
    """Return first-line/frontmatter omissions for a generated Markdown artifact."""
    lines = text.splitlines()
    if not lines or lines[0] != "---":
        return ["first line is not ---"]
    try:
        end = next(index for index, line in enumerate(lines[1:], start=1) if line == "---")
    except StopIteration:
        return ["frontmatter is not closed"]
    frontmatter = lines[1:end]
    problems: list[str] = []
    for field in required_fields:
        if not any(re.match(rf"^{re.escape(field)}:\s*\S", line) for line in frontmatter):
            problems.append(f"missing nonempty {field}")
    return problems


def j5_sections(text: str) -> dict[str, int]:
    """Map exact generated H2 headings to their zero-based line positions."""
    headings: dict[str, int] = {}
    for index, line in enumerate(text.splitlines()):
        match = re.match(r"^##\s+(.+?)\s*$", line)
        if match:
            headings.setdefault(match.group(1), index)
    return headings


def j5_section_body(lines: list[str], start: int) -> list[str]:
    """Return a H2 section body, bounded before the following H2 heading."""
    end = len(lines)
    for index in range(start + 1, len(lines)):
        if re.match(r"^##\s+", lines[index]):
            end = index
            break
    return lines[start + 1 : end]


def j5_has_observable_violation(body: list[str]) -> bool:
    """Require a checkable trigger, not merely a subjective quality statement."""
    return any(
        "->" in line
        or re.search(r"(^|\s)(if|when|without|missing|omit|must|fail|forbid|prohibit|violation)(\s|$)", line, re.IGNORECASE)
        for line in body
        if line.strip() and not line.startswith("#")
    )


def validate_generated_j5_markdown(root: Path) -> tuple[str, str]:
    """Validate J5.1/J5.3, including runtime-specific agent metadata."""
    claude_agent_paths = sorted(root.glob(".claude/agents/**/*.md"))
    codex_agent_paths = sorted(root.glob(".codex/agents/**/*.md"))
    shared_agent_paths = sorted(root.glob("shared/agents/**/*.md"))
    rule_paths = sorted(root.glob(".codex/rules/*.md"))
    issues: list[str] = []
    reviews: list[str] = []

    if not claude_agent_paths and not codex_agent_paths and not shared_agent_paths:
        issues.append("missing .codex/agents/**/*.md")
    for path in [*claude_agent_paths, *codex_agent_paths, *shared_agent_paths]:
        text = read_text(path)
        lines = text.splitlines()
        problems = j5_frontmatter_problems(text, ("name", "description"))
        if path in claude_agent_paths:
            problems.extend(j5_frontmatter_problems(text, ("model",)))
        elif path in codex_agent_paths:
            problems.extend(j5_frontmatter_problems(text, ("agent_type",)))
            relative = path.relative_to(root / ".codex/agents").with_suffix(".toml")
            paired_toml = root / "agents" / relative
            paired, paired_error = parse_toml(paired_toml)
            if paired_error:
                problems.append(f"paired TOML parse/missing: {relpath(paired_toml)}")
            elif not isinstance(paired.get("model"), str) or not paired["model"].strip():
                problems.append(f"paired TOML missing model: {relpath(paired_toml)}")
        headings = j5_sections(text)
        required = ("Reasoning", "Workflow", "Self-Critique", "Boundaries", "Uncertainty Protocol", "Examples")
        duplicates = [
            heading for heading in required
            if len(re.findall(rf"^##[ \t]+{re.escape(heading)}[ \t]*$", text, re.MULTILINE)) > 1
        ]
        if duplicates:
            problems.append(f"duplicate H2: {', '.join(duplicates)}")
        missing = [heading for heading in required if heading not in headings]
        if missing:
            problems.append(f"missing H2: {', '.join(missing)}")
        elif not (headings["Reasoning"] < headings["Workflow"] < headings["Self-Critique"]):
            problems.append("Reasoning < Workflow < Self-Critique order failed")
        else:
            section_names = list(headings)
            start = section_names.index("Reasoning")
            if section_names[start : start + 3] != list(required[:3]):
                problems.append("Reasoning, Workflow, Self-Critique must be adjacent H2 sections")
        for heading in required:
            if heading in headings and not any(
                line.strip() and not line.startswith("#")
                for line in j5_section_body(lines, headings[heading])
            ):
                problems.append(f"empty {heading}")
        duplicate_gates = [
            heading for heading in headings
            if re.fullmatch(r"(?:Preflight|Verification)(?: Gate)?", heading)
        ]
        if duplicate_gates:
            problems.append(f"duplicate contract gates: {', '.join(duplicate_gates)}")
        if "Examples" in headings:
            body = j5_section_body(lines, headings["Examples"])
            boundary_content = False
            in_boundary = False
            for line in body:
                match = re.match(r"^#{3,}\s+(.+?)\s*$", line)
                if match:
                    in_boundary = bool(re.search(r"rejection|boundary|defer|escalat", match.group(1), re.IGNORECASE))
                elif in_boundary and line.strip() and not line.startswith("#"):
                    boundary_content = True
            if not boundary_content:
                problems.append("Examples missing nonempty rejection/defer/escalation boundary case")
        if len(lines) > 300:
            reviews.append(f"{relpath(path)}: {len(lines)} lines exceeds 300")
        if problems:
            issues.append(f"{relpath(path)}: {', '.join(problems)}")

    if not rule_paths:
        issues.append("missing .codex/rules/*.md")
    for path in rule_paths:
        text = read_text(path)
        lines = text.splitlines()
        problems = j5_frontmatter_problems(text, ("name", "description"))
        headings = j5_sections(text)
        for heading in ("Violation Determination", "Exceptions"):
            if heading not in headings:
                problems.append(f"missing H2: {heading}")
                continue
            body = j5_section_body(lines, headings[heading])
            if not any(line.strip() and not line.startswith("#") for line in body):
                problems.append(f"empty {heading}")
            elif heading == "Violation Determination" and not j5_has_observable_violation(body):
                problems.append("non-observable Violation Determination")
        if len(lines) > 100:
            reviews.append(f"{relpath(path)}: {len(lines)} lines exceeds 100")
        if problems:
            issues.append(f"{relpath(path)}: {', '.join(problems)}")

    for path in sorted(root.glob(".codex/skills/**/SKILL.md")):
        count = len(read_text(path).splitlines())
        if count > 200:
            reviews.append(f"{relpath(path)}: {count} lines exceeds 200")
    review_evidence = "; REVIEW_REQUIRED: " + "; ".join(reviews) + "; independent usefulness verdict required" if reviews else ""
    if issues:
        return "FAIL", "; ".join(issues[:6]) + review_evidence
    if reviews:
        return "REVIEW_REQUIRED", review_evidence.removeprefix("; REVIEW_REQUIRED: ")
    return "PASS", (
        f"J5.1: Claude={len(claude_agent_paths)}, Codex={len(codex_agent_paths)}, "
        f"shared={len(shared_agent_paths)} agents; J5.3: {len(rule_paths)} rules"
    )


def validate_active_runtime_vocabulary(root: Path, cfg: dict, registry_entries: list[tuple[str, str, Path]]) -> tuple[str, str]:
    """Scan active configs plus each registry-linked authoritative playbook."""
    paths = [root / ".codex/config.toml"]
    paths.extend(path for _, _, path in registry_entries)
    issues: list[str] = []
    for path in paths:
        data, err = parse_toml(path)
        if err:
            issues.append(f"{relpath(path)} parse error")
            continue
        if path == root / ".codex/config.toml":
            agents = data.get("agents", {})
            if isinstance(agents, dict):
                for key in ("max_threads", "max_depth"):
                    if key in agents:
                        issues.append(f"{relpath(path)} legacy agents.{key}")
            if "disable_response_storage" in data:
                issues.append(f"{relpath(path)} legacy disable_response_storage")
            if str(data.get("approval_policy", "")).lower() == "on-failure":
                issues.append(f"{relpath(path)} deprecated approval_policy=on-failure")
        instructions = data.get("developer_instructions")
        if isinstance(instructions, str):
            for tool, pattern in STALE_RUNTIME_PATTERNS:
                if pattern.search(instructions):
                    issues.append(f"{relpath(path)} stale runtime tool {tool}")
    playbooks = 0
    for _, _, config_path in registry_entries:
        try:
            relative = config_path.resolve().relative_to((root / "agents").resolve())
        except ValueError:
            issues.append(f"{relpath(config_path)} is outside agents/ and cannot map to a playbook")
            continue
        playbook = root / ".codex/agents" / relative.with_suffix(".md")
        if not playbook.is_file():
            issues.append(f"missing authoritative playbook {relpath(playbook)} for {relpath(config_path)}")
            continue
        data, err = parse_toml(config_path)
        if err:
            continue
        instructions = data.get("developer_instructions")
        expected_reference = ".codex/agents/" + relative.with_suffix(".md").as_posix()
        if not isinstance(instructions, str) or expected_reference not in instructions:
            issues.append(f"broken bootstrap mapping: {relpath(config_path)} does not reference {expected_reference}")
        playbooks += 1
        text = read_text(playbook)
        for tool, pattern in STALE_RUNTIME_PATTERNS:
            if pattern.search(text):
                issues.append(f"{relpath(playbook)} stale runtime tool {tool}")
    if issues:
        return "FAIL", "; ".join(issues[:6])
    return "PASS", f"scanned {len(paths)} active TOMLs and {playbooks} mapped playbooks; no stale fields or tool vocabulary"


