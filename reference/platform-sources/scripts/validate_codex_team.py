def validate_generated_proportional_contract(root: Path) -> tuple[str, str]:
    """Validate future-team contract markers without attempting prose/risk scoring."""
    manifest_path = root / ".codex/docs/format-mapping.manifest.yaml"
    if not manifest_path.is_file():
        return "SKIP", "no future-team proportional-design manifest marker"
    manifest, error = parse_json_document(manifest_path)
    if error:
        return "SKIP", "manifest unavailable for future-team proportional-design marker"
    if not proportional_contract_enabled(manifest):
        return "SKIP", "no future-team proportional-design manifest marker"

    authority, authority_evidence = detect_declared_canonical_authority(root)
    if authority is None:
        return "FAIL", f"authority prerequisite failed: {authority_evidence}"
    requested = manifest.get("requested_runtimes")
    if not isinstance(requested, list) or not requested or any(normalized_authority(value) not in {"claude", "codex"} for value in requested):
        return "FAIL", "future-team manifest lacks requested_runtimes limited to Claude/Codex"
    requested_runtimes = {normalized_authority(value) for value in requested}
    expected_rule_paths = {root / f".{runtime}/rules/proportional-design.md" for runtime in requested_runtimes}
    expected_rule_paths.add(root / f"{AUTHORITY_ROOTS[authority]}rules/proportional-design.md")
    missing_rules = [relpath(path) for path in sorted(expected_rule_paths) if not path.is_file()]

    agent_paths: list[Path] = []
    for runtime in requested_runtimes:
        agent_paths.extend((root / f".{runtime}/agents").glob("**/*.md"))
    if authority == "shared":
        agent_paths.extend((root / "shared/agents").glob("**/*.md"))
    texts = [read_text(path) for path in agent_paths]
    missing_markers: list[str] = []
    if not any(PRODUCER_MARKER in text for text in texts):
        missing_markers.append("conditional producer marker")
    if not any(REVIEWER_MARKER in text for text in texts):
        missing_markers.append("existing-reviewer verdict marker")

    approved_count = manifest.get("approved_role_count")
    generated_count = manifest.get("generated_role_count")
    if not isinstance(approved_count, int) or not isinstance(generated_count, int) or approved_count != generated_count:
        missing_markers.append("unchanged approved/generated role count marker")

    cases = manifest.get("proportional_design_cases")
    supported_cases = isinstance(cases, list) and any(
        isinstance(case, dict)
        and case.get("kind") == "unsupported-blocker"
        and case.get("verdict") == "REJECT"
        for case in cases
    ) and any(
        isinstance(case, dict)
        and case.get("kind") == "high-impact-control"
        and case.get("verdict") == "ACCEPT"
        and isinstance(case.get("evidence"), str)
        and case["evidence"].strip()
        for case in cases
    )
    if not supported_cases:
        missing_markers.append("unsupported-blocker rejection and justified high-impact acceptance markers")
    if missing_rules:
        missing_markers.append(f"missing rule projections: {', '.join(missing_rules)}")
    if missing_markers:
        return "FAIL", "; ".join(missing_markers)
    return "PASS", f"marker={PROPORTIONAL_CONTRACT_MARKER}; requested={','.join(sorted(requested_runtimes))}; roles={approved_count}"


def parse_toml(path: Path) -> tuple[dict, str | None]:
    try:
        with path.open("rb") as fh:
            return tomllib.load(fh), None
    except (OSError, tomllib.TOMLDecodeError) as exc:
        return {}, str(exc)


def path_exists(path: Path) -> bool:
    return path.exists()


def tree_paths(root: Path) -> set[str]:
    """Return a deterministic relative tree, including empty directories."""
    return {
        path.relative_to(root).as_posix()
        for path in root.rglob("*")
    }


def validate_skill_mirror(root: Path, required: bool) -> tuple[str, str]:
    """Check authored/runtime skill mirrors for identical paths and bytes."""
    authored = root / ".codex/skills"
    runtime = root / ".agents/skills"
    authored_present = authored.is_dir()
    runtime_present = runtime.is_dir()
    if not authored_present and not runtime_present:
        return ("FAIL" if required else "SKIP", "neither .codex/skills nor .agents/skills exists")
    if not authored_present or not runtime_present:
        missing = ".codex/skills" if not authored_present else ".agents/skills"
        return "FAIL", f"one-sided skill mirror: missing {missing}"

    authored_tree = tree_paths(authored)
    runtime_tree = tree_paths(runtime)
    if authored_tree != runtime_tree:
        only_authored = sorted(authored_tree - runtime_tree)
        only_runtime = sorted(runtime_tree - authored_tree)
        evidence: list[str] = []
        if only_authored:
            evidence.append(f"only .codex/skills: {', '.join(only_authored[:3])}")
        if only_runtime:
            evidence.append(f"only .agents/skills: {', '.join(only_runtime[:3])}")
        return "FAIL", "; ".join(evidence)

    compared = 0
    for relative in sorted(authored_tree):
        authored_path = authored / relative
        runtime_path = runtime / relative
        if authored_path.is_dir():
            continue
        if not authored_path.is_file() or not runtime_path.is_file():
            return "FAIL", f"non-file mirror mismatch at {relative}"
        compared += 1
        if authored_path.read_bytes() != runtime_path.read_bytes():
            return "FAIL", f"byte mismatch: {relative}"
    return "PASS", f"byte-identical trees; {compared} files"


def extract_audit_table_paths(audit: Path, heading: str) -> set[str]:
    """Extract first-column code paths from a named Markdown audit table."""
    in_section = False
    paths: set[str] = set()
    row_pattern = re.compile(r"^\|\s*`([^`]+)`\s*\|")
    for line in read_text(audit).splitlines():
        if line.startswith("## "):
            in_section = line.strip() == f"## {heading}"
            continue
        if in_section:
            match = row_pattern.match(line)
            if match:
                paths.add(match.group(1))
    return paths


def adaptation_input_problems(root: Path, data: dict, platform: set[str], audit: Path) -> list[str]:
    """Check the three bounded platform inputs and their exact human mapping."""
    known = {
        ".codex/rules/codex-runtime-config.md",
        ".codex/rules/codex-agent-config-patterns.md",
        ".codex/rules/context-isolation.md",
    }
    entries = data.get("adaptation_inputs")
    if not isinstance(entries, list) or not entries:
        return ["missing [[adaptation_inputs]] entries"]
    problems: list[str] = []
    manifest_rows: dict[str, tuple[str, set[str]]] = {}
    for entry in entries:
        path = entry.get("path") if isinstance(entry, dict) else None
        if not isinstance(path, str) or path not in known:
            problems.append(f"unknown adaptation input path: {path!r}")
            continue
        if path in manifest_rows:
            problems.append(f"duplicate adaptation input path: {path}")
            continue
        if path not in platform:
            problems.append(f"adaptation input is not platform-only: {path}")
        if not safe_relative_path(root, path) or not (root / path).is_file():
            problems.append(f"unsafe or missing adaptation input: {path}")
        scope = entry.get("scope")
        if not isinstance(scope, str) or not scope.strip():
            problems.append(f"adaptation input has empty/invalid scope: {path}")
            scope = ""
        targets = entry.get("targets")
        if not isinstance(targets, list) or not targets:
            problems.append(f"adaptation input has empty/invalid targets: {path}")
            targets = []
        checked_targets: set[str] = set()
        for target in targets:
            if not isinstance(target, str) or not target.strip():
                problems.append(f"adaptation input has invalid target: {path}")
                continue
            if target in checked_targets:
                problems.append(f"duplicate adaptation target: {path} -> {target}")
            checked_targets.add(target)
            projection = target == "AGENTS.md" or target.startswith((".codex/", ".agents/skills/", "agents/"))
            if not projection or not safe_relative_path(root, target) or not (root / target).is_file():
                problems.append(f"unsafe or missing Codex projection target: {path} -> {target}")
        manifest_rows[path] = (scope.strip(), checked_targets)
    if set(manifest_rows) != known:
        problems.append("adaptation_inputs must contain all three known platform input paths")

    audit_rows: dict[str, tuple[str, set[str]]] = {}
    in_section = False
    section_count = 0
    header_count = 0
    for line in read_text(audit).splitlines():
        if line.startswith("## "):
            in_section = line.strip() == "## Runtime Adaptation Inputs"
            section_count += int(in_section)
            continue
        if not in_section or not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if cells == ["Input", "Bounded scope", "Projections"]:
            header_count += 1
            continue
        if len(cells) == 3 and all(re.fullmatch(r":?-+:?", cell) for cell in cells):
            continue
        if len(cells) != 3:
            problems.append("malformed audit Runtime Adaptation Inputs row")
            continue
        input_match = re.fullmatch(r"`([^`]+)`", cells[0])
        target_cells = re.split(r"\s*<br>\s*", cells[2])
        target_matches = [re.fullmatch(r"`([^`]+)`", cell) for cell in target_cells]
        if not input_match or not cells[1] or not all(target_matches):
            problems.append("malformed audit Runtime Adaptation Inputs path/scope/targets")
            continue
        path = input_match.group(1)
        targets = [match.group(1) for match in target_matches if match]
        if path in audit_rows:
            problems.append(f"duplicate audit adaptation input: {path}")
        if len(targets) != len(set(targets)):
            problems.append(f"duplicate audit adaptation target: {path}")
        audit_rows[path] = (cells[1], set(targets))
    if section_count != 1 or header_count != 1:
        problems.append("audit requires one Runtime Adaptation Inputs table with Input/Bounded scope/Projections")
    if manifest_rows != audit_rows:
        problems.append("adaptation_inputs scope/targets differ from audit Runtime Adaptation Inputs")
    return problems


def validate_m5_inventory(root: Path) -> tuple[str, str]:
    """Validate the machine-readable M5 inventory against its human audit."""
    manifest = root / ".codex/docs/claude-adaptation-manifest.toml"
    audit = root / ".codex/docs/claude-adaptation-audit.md"
    data, err = parse_toml(manifest)
    if err:
        return "FAIL", f"{relpath(manifest)} parse error: {err}"
    if not audit.is_file():
        return "FAIL", f"missing {relpath(audit)}"

    def manifest_paths(key: str) -> tuple[set[str], list[str]]:
        entries = data.get(key)
        if not isinstance(entries, list):
            return set(), [f"missing [[{key}]] entries"]
        paths: set[str] = set()
        issues: list[str] = []
        for entry in entries:
            path = entry.get("path") if isinstance(entry, dict) else None
            if not isinstance(path, str) or not path:
                issues.append(f"{key} entry missing path")
            elif path in paths:
                issues.append(f"duplicate {key} path: {path}")
            else:
                paths.add(path)
        return paths, issues

    platform, problems = manifest_paths("platform_only")
    omitted, omitted_problems = manifest_paths("deliberately_not_copied")
    problems.extend(omitted_problems)
    audit_platform = extract_audit_table_paths(audit, "Codex-Only Inventory")
    audit_omitted = extract_audit_table_paths(audit, "Deliberately Not Copied")
    if platform != audit_platform:
        problems.append("platform_only paths differ from audit Codex-Only Inventory")
    if omitted != audit_omitted:
        problems.append("deliberately_not_copied paths differ from audit Deliberately Not Copied")
    missing_paths = [path for path in sorted(platform) if not (root / path).exists()]
    if missing_paths:
        problems.append(f"platform-only paths missing: {', '.join(missing_paths[:4])}")
    problems.extend(adaptation_input_problems(root, data, platform, audit))
    if problems:
        return "FAIL", "; ".join(problems[:6])
    return "PASS", f"manifest/audit agree; {len(platform)} platform-only and {len(omitted)} deliberately-not-copied paths; 3 bounded adaptation inputs"


